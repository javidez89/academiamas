import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MARKER = '-- Generated by tools/generate-assessment-registry.mjs. Do not edit manually.';

function sqlText(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function fingerprint(value) {
  return createHash('sha256').update(JSON.stringify(value)).digest('hex');
}

function normalizeLineEndings(value) {
  return String(value).replaceAll('\r\n', '\n');
}

async function loadCourses() {
  const entries = await fs.readdir(path.join(ROOT, 'courses'), { withFileTypes: true });
  const courses = [];
  for (const entry of entries.filter((item) => item.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    const filename = path.join(ROOT, 'courses', entry.name, 'course-data.js');
    try {
      await fs.access(filename);
    } catch {
      continue;
    }

    let registered = null;
    const sandbox = { AcademyRegistry: { register: (key, course) => { registered = { key, course }; } } };
    vm.createContext(sandbox);
    vm.runInContext(await fs.readFile(filename, 'utf8'), sandbox, { filename });
    assert.ok(registered, `${entry.name}: el archivo no registró el curso.`);
    assert.equal(registered.key, entry.name, `${entry.name}: la clave registrada no coincide con la carpeta.`);
    courses.push(registered);
  }
  return courses;
}

function normalizeCourse({ key, course }) {
  const questions = Array.isArray(course.questions) ? course.questions : [];
  const blueprint = course.blueprint || {};
  assert.ok(questions.length, `${key}: banco vacío.`);
  assert.ok(Number(blueprint.totalQuestions) > 0, `${key}: totalQuestions inválido.`);
  assert.ok(Number(blueprint.passingScore) > 0, `${key}: passingScore inválido.`);
  assert.ok(Number(blueprint.minutes) > 0, `${key}: minutes inválido.`);
  assert.ok(blueprint.matrix && typeof blueprint.matrix === 'object', `${key}: matriz ausente.`);

  const ids = new Set();
  const normalizedQuestions = questions.map((question) => {
    const questionId = String(question.id || '').trim();
    assert.ok(questionId && !ids.has(questionId), `${key}: ID duplicado o vacío ${questionId}.`);
    ids.add(questionId);
    const correct = [...new Set((question.correct || []).map(Number))].sort((a, b) => a - b);
    assert.ok(correct.length && correct.every((index) => Number.isInteger(index) && index >= 0 && index <= 3), `${key}/${questionId}: respuesta inválida.`);
    const item = {
      courseKey: key,
      questionId,
      chapterId: Number(question.chapter),
      kLevel: String(question.k || ''),
      learningObjective: String(question.lo || ''),
      correct,
      points: Number(question.points || 1),
      fingerprint: fingerprint({
        stem: question.stem,
        options: question.options,
        correct,
        chapter: question.chapter,
        k: question.k,
        lo: question.lo,
        points: Number(question.points || 1)
      })
    };
    assert.ok(Number.isInteger(item.chapterId) && item.chapterId > 0, `${key}/${questionId}: capítulo inválido.`);
    assert.match(item.kLevel, /^K[1-9][0-9]*$/, `${key}/${questionId}: nivel K inválido.`);
    assert.ok(item.learningObjective, `${key}/${questionId}: objetivo vacío.`);
    assert.ok(item.points > 0, `${key}/${questionId}: puntos inválidos.`);
    return item;
  });

  const revision = fingerprint({
    key,
    blueprint,
    questions: normalizedQuestions.map(({ fingerprint: itemFingerprint, ...item }) => ({ ...item, fingerprint: itemFingerprint }))
  }).slice(0, 24);
  const matrixTotal = Object.values(blueprint.matrix).reduce((courseTotal, levels) => (
    courseTotal + Object.values(levels).reduce((chapterTotal, count) => chapterTotal + Number(count || 0), 0)
  ), 0);
  assert.equal(matrixTotal, Number(blueprint.totalQuestions), `${key}: la matriz no suma totalQuestions.`);

  return {
    key,
    revision,
    questions: normalizedQuestions,
    blueprint: {
      totalQuestions: Number(blueprint.totalQuestions),
      totalPoints: Number(blueprint.totalPoints || blueprint.totalQuestions),
      passingPoints: Number(blueprint.passingScore),
      durationMinutes: Number(blueprint.minutes),
      matrix: blueprint.matrix
    }
  };
}

function blueprintSql(course) {
  const value = course.blueprint;
  return `(${sqlText(course.key)}, ${value.totalQuestions}, ${value.totalPoints.toFixed(2)}, ${value.passingPoints.toFixed(2)}, ${value.durationMinutes}, ${sqlText(JSON.stringify(value.matrix))}::jsonb, ${sqlText(course.revision)})`;
}

function questionSql(course, question) {
  const indices = `array[${question.correct.join(', ')}]::smallint[]`;
  return `(${sqlText(course.key)}, ${sqlText(question.questionId)}, ${question.chapterId}, ${sqlText(question.kLevel)}, ${sqlText(question.learningObjective)}, ${indices}, ${question.points.toFixed(2)}, ${sqlText(question.fingerprint)}, ${sqlText(course.revision)}, true)`;
}

function renderSql(courses) {
  const totalQuestions = courses.reduce((total, course) => total + course.questions.length, 0);
  const lines = [
    MARKER,
    `-- Courses: ${courses.length}. Active questions: ${totalQuestions}.`,
    '',
    'insert into private.assessment_blueprints (',
    '  course_key, total_questions, total_points, passing_points, duration_minutes, matrix, bank_revision',
    ') values',
    courses.map(blueprintSql).join(',\n'),
    'on conflict (course_key) do update set',
    '  total_questions = excluded.total_questions,',
    '  total_points = excluded.total_points,',
    '  passing_points = excluded.passing_points,',
    '  duration_minutes = excluded.duration_minutes,',
    '  matrix = excluded.matrix,',
    '  bank_revision = excluded.bank_revision,',
    '  updated_at = now();',
    ''
  ];

  for (const course of courses) {
    lines.push(
      `update private.assessment_question_registry set active = false, updated_at = now() where course_key = ${sqlText(course.key)};`,
      ''
    );
    const chunks = [];
    for (let index = 0; index < course.questions.length; index += 200) {
      chunks.push(course.questions.slice(index, index + 200));
    }
    for (const chunk of chunks) {
      lines.push(
        'insert into private.assessment_question_registry (',
        '  course_key, question_id, chapter_id, k_level, learning_objective, correct_indices, points,',
        '  content_fingerprint, bank_revision, active',
        ') values',
        chunk.map((question) => questionSql(course, question)).join(',\n'),
        'on conflict (course_key, question_id) do update set',
        '  chapter_id = excluded.chapter_id,',
        '  k_level = excluded.k_level,',
        '  learning_objective = excluded.learning_objective,',
        '  correct_indices = excluded.correct_indices,',
        '  points = excluded.points,',
        '  content_fingerprint = excluded.content_fingerprint,',
        '  bank_revision = excluded.bank_revision,',
        '  active = true,',
        '  updated_at = now();',
        ''
      );
    }
  }

  lines.push('do $$', 'declare', '  v_count integer;', 'begin');
  for (const course of courses) {
    lines.push(
      `  select count(*) into v_count from private.assessment_question_registry where course_key = ${sqlText(course.key)} and active and bank_revision = ${sqlText(course.revision)};`,
      `  if v_count <> ${course.questions.length} then raise exception 'Assessment registry mismatch for ${course.key}'; end if;`
    );
  }
  lines.push('end;', '$$;', '');
  return lines.join('\n');
}

const courses = (await loadCourses()).map(normalizeCourse);
const sql = renderSql(courses);
const mode = process.argv[2];
const destination = process.argv[3] ? path.resolve(ROOT, process.argv[3]) : null;

if (mode === '--write' && destination) {
  await fs.writeFile(destination, sql, 'utf8');
  console.log(`Assessment registry generated: ${courses.length} cursos, ${courses.reduce((sum, course) => sum + course.questions.length, 0)} preguntas.`);
} else if (mode === '--check' && destination) {
  const current = await fs.readFile(destination, 'utf8');
  assert.equal(
    normalizeLineEndings(current),
    normalizeLineEndings(sql),
    `El registro ${path.relative(ROOT, destination)} no coincide con los bancos actuales.`
  );
  console.log(`Assessment registry OK: ${courses.length} cursos y ${courses.reduce((sum, course) => sum + course.questions.length, 0)} preguntas.`);
} else {
  throw new Error('Usa --write <migración.sql> o --check <migración.sql>.');
}
