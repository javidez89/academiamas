import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'supabase', 'functions', '_shared', 'course-audio-manifest.ts');

function loadCourse(key) {
  let course;
  const file = path.join(root, 'courses', key, 'course-data.js');
  vm.runInNewContext(fs.readFileSync(file, 'utf8'), {
    AcademyRegistry: { register: (_key, data) => { course = data; } }
  });
  return course;
}

function normalizeText(value) {
  return String(value || '').normalize('NFKC').replace(/\s+/g, ' ').trim();
}

function splitNarrationText(value, limit = 3_900) {
  const text = normalizeText(value);
  if (!text) return [];
  const chunks = [];
  let remaining = text;
  while (remaining.length > limit) {
    const window = remaining.slice(0, limit + 1);
    const sentenceBoundary = Math.max(window.lastIndexOf('. '), window.lastIndexOf('? '), window.lastIndexOf('! '), window.lastIndexOf('; '));
    const wordBoundary = window.lastIndexOf(' ');
    const boundary = sentenceBoundary >= Math.floor(limit * 0.55) ? sentenceBoundary + 1 : wordBoundary >= Math.floor(limit * 0.55) ? wordBoundary : limit;
    chunks.push(remaining.slice(0, boundary).trim());
    remaining = remaining.slice(boundary).trim();
  }
  if (remaining) chunks.push(remaining);
  return chunks;
}

function chapterNarration(chapter) {
  const sections = (chapter.theorySections || []).flatMap((section) => [
    section.title,
    section.body,
    ...(section.bullets || [])
  ]);
  const caseStudy = chapter.caseStudy ? [
    `Caso práctico: ${chapter.caseStudy.title || ''}`,
    chapter.caseStudy.context,
    chapter.caseStudy.challenge,
    chapter.caseStudy.approach,
    chapter.caseStudy.evidence
  ] : [];
  return normalizeText([
    `Capítulo ${chapter.id}. ${chapter.title}.`,
    chapter.summary,
    ...sections,
    ...caseStudy,
    ...(chapter.examples || [])
  ].filter(Boolean).join(' '));
}

function objectiveNarration(objective) {
  return normalizeText([
    `Objetivo de aprendizaje ${objective.lo}, nivel ${objective.k}.`,
    objective.text,
    objective.theory,
    objective.remember ? `Recuerda: ${objective.remember}` : '',
    objective.example ? `Escenario práctico: ${objective.example}` : '',
    objective.trap ? `Evita esta confusión: ${objective.trap}` : ''
  ].filter(Boolean).join(' '));
}

function chapterReferenceNarration(chapter) {
  return normalizeText([
    `Material de estudio ampliado del capítulo ${chapter.id}. ${chapter.title}.`,
    chapter.completeSyllabusText
  ].filter(Boolean).join(' '));
}

function objectiveReferenceNarration(objective) {
  return normalizeText([
    `Contenido de referencia del objetivo de aprendizaje ${objective.lo}.`,
    objective.sourceText,
    objective.syllabusExtract
  ].filter(Boolean).join(' '));
}

function digest(text) {
  return crypto.createHash('sha256').update(text).digest('hex');
}

function addNarration(content, contentId, text) {
  const chunks = splitNarrationText(text);
  chunks.forEach((chunk, index) => {
    const segmentId = chunks.length > 1 ? `${contentId}-part-${index + 1}` : contentId;
    content[segmentId] = digest(chunk);
  });
}

const manifest = {};
const coursesRoot = path.join(root, 'courses');
for (const entry of fs.readdirSync(coursesRoot, { withFileTypes: true })) {
  if (!entry.isDirectory() || entry.name.startsWith('_')) continue;
  if (!fs.existsSync(path.join(coursesRoot, entry.name, 'course-data.js'))) continue;
  const course = loadCourse(entry.name);
  const content = {};
  for (const chapter of course.chapters || []) {
    addNarration(content, `chapter-${chapter.id}`, chapterNarration(chapter));
    if (chapter.completeSyllabusText) addNarration(content, `chapter-reference-${chapter.id}`, chapterReferenceNarration(chapter));
  }
  for (const objective of course.objectives || []) {
    addNarration(content, `lo-${String(objective.lo).toLowerCase()}`, objectiveNarration(objective));
    if (objective.syllabusExtract) addNarration(content, `lo-reference-${String(objective.lo).toLowerCase()}`, objectiveReferenceNarration(objective));
  }
  manifest[entry.name] = content;
}

const generated = `// Generated by tools/generate-audio-manifest.mjs. Do not edit manually.\n`
  + `export const COURSE_AUDIO_HASHES: Readonly<Record<string, Readonly<Record<string, string>>>> = Object.freeze(${JSON.stringify(manifest, null, 2)});\n\n`
  + `export function allowedCourseAudioHash(courseKey: string, contentId: string, hash: string): boolean {\n`
  + `  return COURSE_AUDIO_HASHES[courseKey]?.[contentId] === hash;\n`
  + `}\n`;

fs.writeFileSync(output, generated, 'utf8');
console.log(`Audio manifest OK: ${Object.keys(manifest).length} cursos.`);
